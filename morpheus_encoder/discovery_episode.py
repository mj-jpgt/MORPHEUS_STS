"""Observed-only episode contract for discovery experiments.

The contract is deliberately smaller than :mod:`dbench.world`: a discovery
method receives observations, an optional measured response, declared context,
and explicit row partitions.  Oracle design fields never enter this boundary.
This gives proposal, replication, and null code a serialisable object whose
content identity is independent of benchmark answers.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import json
from typing import Any, Mapping

import numpy as np

from .world_adapter import world_to_inputs


def _readonly_array(value, *, name: str, n: int | None = None) -> np.ndarray:
    """Copy a row-aligned value into an immutable, C-contiguous array."""
    array = np.ascontiguousarray(np.asarray(value))
    if array.ndim == 0:
        raise ValueError("%s must have a row dimension" % name)
    if n is not None and array.shape[0] != n:
        raise ValueError("%s has %d rows; expected %d" % (name, array.shape[0], n))
    if array.dtype.kind not in "biufUS":
        raise TypeError("%s has unsupported dtype %s" % (name, array.dtype))
    array = array.copy()
    array.setflags(write=False)
    return array


def _canonical_value(value: Any) -> Any:
    """Canonical JSON-compatible representation for context and hashing."""
    if isinstance(value, np.ndarray):
        return {"__array__": _array_digest(value)}
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, Mapping):
        return {str(k): _canonical_value(value[k]) for k in sorted(value, key=str)}
    if isinstance(value, (tuple, list)):
        return [_canonical_value(v) for v in value]
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return str(value)


def _freeze_value(value: Any) -> Any:
    """Retain readable context while preventing accidental in-place mutation."""
    if isinstance(value, np.ndarray):
        out = np.ascontiguousarray(value).copy()
        out.setflags(write=False)
        return out
    if isinstance(value, Mapping):
        return {str(k): _freeze_value(v) for k, v in value.items()}
    if isinstance(value, (tuple, list)):
        return tuple(_freeze_value(v) for v in value)
    if isinstance(value, np.generic):
        return value.item()
    return value


def _array_digest(array: np.ndarray) -> dict:
    array = np.ascontiguousarray(np.asarray(array))
    return {
        "dtype": array.dtype.str,
        "shape": list(array.shape),
        "sha256": hashlib.sha256(array.tobytes(order="C")).hexdigest(),
    }


def _digest_update(hasher, name: str, array: np.ndarray) -> None:
    hasher.update(name.encode("utf-8"))
    hasher.update(b"\0")
    hasher.update(json.dumps(_array_digest(array), sort_keys=True).encode("utf-8"))
    hasher.update(b"\0")
    hasher.update(np.ascontiguousarray(array).tobytes(order="C"))


@dataclass(frozen=True)
class EpisodePartitions:
    """Disjoint, exhaustive row roles fixed before candidate proposal.

    ``proposal`` can choose candidates, ``replication`` can only evaluate the
    frozen candidate list, and ``null`` is reserved for structured-null
    evaluation.  Requiring all three roles prevents a caller from quietly
    recycling discovery rows as validation rows.
    """

    proposal: np.ndarray
    replication: np.ndarray
    null: np.ndarray

    def __post_init__(self) -> None:
        for role in ("proposal", "replication", "null"):
            raw = np.asarray(getattr(self, role))
            if raw.ndim != 1:
                raise ValueError("%s partition must be a 1-D vector" % role)
            # `null` alone may be empty: a real-substrate episode whose
            # structured nulls are generated by transforming the
            # `replication` rows in place (`episode_null_generators`) has no
            # separate row role to reserve for them.  `DiscoveryEpisode`
            # gates this on an explicit `metadata["null_source"]` flag so an
            # empty null partition is never silently accepted elsewhere.
            if role != "null" and raw.size == 0:
                raise ValueError("%s partition must be a non-empty vector" % role)
            if raw.size:
                if raw.dtype.kind not in "iu":
                    raise TypeError("%s partition must contain integer row indices" % role)
                if np.any(raw < 0) or len(np.unique(raw)) != len(raw):
                    raise ValueError("%s partition has negative or duplicate indices" % role)
            value = np.ascontiguousarray(raw.astype(np.int64, copy=False)).copy()
            value.setflags(write=False)
            object.__setattr__(self, role, value)

    def validate(self, n: int) -> None:
        all_rows = np.concatenate((self.proposal, self.replication, self.null))
        if np.any(all_rows >= n):
            raise ValueError("partition contains a row outside [0, %d)" % n)
        if len(np.unique(all_rows)) != len(all_rows):
            raise ValueError("proposal, replication, and null rows must be disjoint")
        if len(all_rows) != n or not np.array_equal(np.sort(all_rows), np.arange(n)):
            raise ValueError("partitions must exhaust every episode row exactly once")

    def as_dict(self) -> dict[str, np.ndarray]:
        return {"proposal": self.proposal, "replication": self.replication,
                "null": self.null}


@dataclass(frozen=True)
class DiscoveryEpisode:
    """Immutable observed data passed into a discovery workflow.

    ``context`` may contain row-aligned ``coords``, ``time``, ``neighbors``,
    ``scale`` and environmental labels.  The named fields are intentionally
    generic; domains can add serialisable context without changing the core.
    """

    modalities: Mapping[str, np.ndarray]
    partitions: EpisodePartitions
    response: np.ndarray | None = None
    context: Mapping[str, Any] = field(default_factory=dict)
    metadata: Mapping[str, Any] = field(default_factory=dict)
    schema_version: str = "discovery_episode/v1"

    def __post_init__(self) -> None:
        if not self.modalities:
            raise ValueError("episode needs at least one observed modality")
        converted = {str(k): _readonly_array(v, name="modality %s" % k)
                     for k, v in sorted(self.modalities.items(), key=lambda x: str(x[0]))}
        n = next(iter(converted.values())).shape[0]
        for key, value in converted.items():
            if value.shape[0] != n:
                raise ValueError("modalities do not share scientific units (%s)" % key)
            if value.dtype.kind in "f" and not np.all(np.isfinite(value)):
                raise ValueError("modality %s contains non-finite values" % key)
        response = None if self.response is None else _readonly_array(
            self.response, name="response", n=n)
        if response is not None and response.dtype.kind in "f" and not np.all(np.isfinite(response)):
            raise ValueError("response contains non-finite values")
        self.partitions.validate(n)
        if self.partitions.null.size == 0 and dict(self.metadata).get("null_source") != "replication_structured":
            raise ValueError(
                "an empty null partition requires metadata['null_source'] == "
                "'replication_structured' (nulls generated from replication rows)")
        object.__setattr__(self, "modalities", converted)
        object.__setattr__(self, "response", response)
        object.__setattr__(self, "context", _freeze_value(dict(self.context)))
        object.__setattr__(self, "metadata", _freeze_value(dict(self.metadata)))

    @property
    def n_rows(self) -> int:
        return next(iter(self.modalities.values())).shape[0]

    def content_hash(self) -> str:
        """Hash exactly the data readable by a discovery method."""
        h = hashlib.sha256(self.schema_version.encode("utf-8"))
        for name, value in self.modalities.items():
            _digest_update(h, "modality:" + name, value)
        if self.response is not None:
            _digest_update(h, "response", self.response)
        for role, rows in self.partitions.as_dict().items():
            _digest_update(h, "partition:" + role, rows)
        h.update(json.dumps(_canonical_value(self.context), sort_keys=True,
                            separators=(",", ":")).encode("utf-8"))
        h.update(json.dumps(_canonical_value(self.metadata), sort_keys=True,
                            separators=(",", ":")).encode("utf-8"))
        return h.hexdigest()

    def receipt_identity(self) -> dict[str, Any]:
        """Small serialisable identity appropriate for immutable receipts."""
        return {"schema_version": self.schema_version, "content_sha256": self.content_hash(),
                "n_rows": self.n_rows,
                "modalities": {k: list(v.shape) for k, v in self.modalities.items()},
                "has_response": self.response is not None,
                "partition_sizes": {k: int(v.size) for k, v in self.partitions.as_dict().items()}}

    def observed_matrix(self, *, modalities: tuple[str, ...] | None = None) -> np.ndarray:
        """Return a deterministic concatenation of observed modalities.

        This is intentionally a convenience boundary rather than a claim that
        concatenation is a multiscale model.  Rich adapters may retain separate
        modalities; generic discovery baselines need a reproducible flat view.
        """
        names = tuple(sorted(self.modalities) if modalities is None else modalities)
        if not names or any(name not in self.modalities for name in names):
            raise ValueError("requested modalities must be a non-empty subset of episode modalities")
        return np.column_stack([np.asarray(self.modalities[name]).reshape(self.n_rows, -1)
                                for name in names]).astype(float, copy=False)

    def numeric_context_matrix(self) -> np.ndarray | None:
        """Flatten declared numeric, row-aligned context without guessing units."""
        pieces = []
        for key in sorted(self.context):
            value = self.context[key]
            if isinstance(value, np.ndarray) and value.shape[0] == self.n_rows:
                numeric = np.asarray(value)
                if numeric.dtype.kind in "biuf":
                    pieces.append(numeric.reshape(self.n_rows, -1).astype(float, copy=False))
        return None if not pieces else np.column_stack(pieces)

    def split_arrays(self, role: str) -> tuple[np.ndarray, np.ndarray, np.ndarray | None]:
        """Expose one frozen role to generic discovery code, never mixing rows."""
        if self.response is None:
            raise ValueError("this episode has no measured response")
        if role not in {"proposal", "replication", "null"}:
            raise KeyError("role must be proposal, replication, or null")
        rows = getattr(self.partitions, role)
        context = self.numeric_context_matrix()
        return (self.observed_matrix()[rows], np.asarray(self.response, dtype=float).reshape(-1)[rows],
                None if context is None else context[rows])


#: E4 / discoadd "Multiscale structure requires an explicit scale graph":
#: every observable/latent variable should carry entity type, spatial
#: support, temporal support, measurement modality, biological/physical
#: scale and (when known) containment/mapping relations. Kept in sync with
#: the analogous constant in `dbench.object_cards`.
SCALE_FIELDS = ("entity_type", "spatial_support", "temporal_support",
               "modality", "biological_scale", "containment")


def validate_scale(scale: Mapping[str, Any]) -> dict:
    """Advisory schema check for an episode's `metadata["scale"]` record.

    This is deliberately advisory, not enforced: it is never called from
    `DiscoveryEpisode.__post_init__`, so an episode with no declared scale
    metadata at all, or an incomplete one, remains a perfectly valid
    episode. A caller who wants the discoadd scale-graph discipline calls
    this explicitly and gets back exactly which field(s) are missing --
    never a bare `True`/`False` that hides which part of the scale graph is
    unknown.

    Returns ``{"valid": bool, "missing": [...field names...], "fields":
    {field: value_or_None}}``.
    """
    if not isinstance(scale, Mapping):
        raise TypeError("scale must be a mapping with keys %r" % (SCALE_FIELDS,))
    missing = [f for f in SCALE_FIELDS if scale.get(f) is None]
    return {"valid": not missing, "missing": missing,
           "fields": {f: scale.get(f) for f in SCALE_FIELDS}}


def world_to_episode(world, *, partitions: EpisodePartitions,
                     scale: Mapping[str, Any] | None = None,
                     metadata: Mapping[str, Any] | None = None) -> DiscoveryEpisode:
    """Convert a blinded benchmark world using observed fields only.

    The function deliberately delegates modality/environment/structure parsing
    to :func:`world_to_inputs`.  It reads only the publicly measured response
    in addition to that adapter's observed fields.  ``scale`` is explicit so a
    caller, rather than an adapter guess, declares physical units or resolution.
    """
    inputs = world_to_inputs(world, include_env=True)
    context: dict[str, Any] = {"env_columns": list(inputs.meta["env_columns"]),
                               "env_role": inputs.meta["env_role"],
                               "scale": dict(scale or {})}
    for name, value in inputs.structure.items():
        if hasattr(value, "detach"):
            value = value.detach().cpu().numpy()
        context[name] = value
    if inputs.env is not None:
        context["environment"] = inputs.env.detach().cpu().numpy()
    response = getattr(world, "target", None)
    return DiscoveryEpisode(
        modalities={k: v.detach().cpu().numpy() for k, v in inputs.X.items()},
        response=response, partitions=partitions, context=context,
        metadata={"name": inputs.meta["name"], "family": inputs.meta["family"],
                  "domain": inputs.meta["domain"], **dict(metadata or {})},
    )
