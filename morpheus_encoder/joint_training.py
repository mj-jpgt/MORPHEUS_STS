"""Observed-data training seam for frozen differentiable object proposals.

The symbolic compiler is intentionally not in this module.  At each call a
proposal environment forms a soft object bank, that dictionary is detached and
frozen, and the *same* dictionary is opened on proposal, independent
replication, and structurally matched null environments.  The numerical
forward values are exactly the frozen values.  A straight-through path from
the proposal bank nevertheless lets gradients update object formation.

The only supervision accepted here is an observed response vector.  There is
no benchmark-label, object-identity, or domain-model input.  Consequently this
is suitable for real-substrate calibration as well as for application data;
claim rendering and final certification remain separate, post-training steps.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Mapping

import torch
import torch.nn as nn

from .joint_objects import (
    DifferentiableObjectFormation,
    FrozenObjectSelection,
    JointObjectOutput,
)
from .object_critic import ObjectCriticOutput, ReplicationObjectCritic


@dataclass
class JointTrainingOutput:
    """One differentiable observed-data objective and its locked dictionary."""

    loss: torch.Tensor
    objective: torch.Tensor
    critic: ObjectCriticOutput
    selection: FrozenObjectSelection
    proposal_values: torch.Tensor
    replication_values: torch.Tensor
    null_values: torch.Tensor
    proposal_evidence: torch.Tensor
    replication_evidence: torch.Tensor
    null_evidence: torch.Tensor
    # Candidate order is always atomic readout coordinates first, followed by
    # the proposal-frozen relational objects.  This is deliberately carried
    # with the numerical values so a training receipt cannot later confuse a
    # learned relation with the atomic channel the compiler actually reads.
    candidate_provenance: tuple[Mapping[str, object], ...]
    atomic_candidate_count: int
    relational_candidate_count: int
    relational_proposal_values: torch.Tensor
    relational_replication_values: torch.Tensor
    relational_null_values: torch.Tensor
    # Optional parent evidence is deliberately not generated by this harness.
    # It must be supplied as an independently predeclared, lower-complexity
    # candidate family; the critic records its candidate-level penalty.


def observed_signed_evidence(values: torch.Tensor, response: torch.Tensor,
                             *, eps: float = 1e-6) -> torch.Tensor:
    """Return differentiable per-observation signed association evidence.

    ``values`` has shape ``(observations, candidates)`` and ``response`` is
    one observed scalar per observation, shape ``(observations,)`` or
    ``(observations, 1)``.  Both are standardized *within their environment*,
    so their mean product is a bounded correlation-like association.  Constant
    candidates or responses receive zero rather than a numerical exception.
    This function never infers a response from a hidden label.
    """
    if values.ndim != 2 or not values.is_floating_point():
        raise ValueError("values must be floating point with shape (observations, candidates)")
    if values.shape[0] < 2:
        raise ValueError("at least two observations are required for signed evidence")
    if response.ndim == 2 and response.shape[1] == 1:
        response = response[:, 0]
    if response.ndim != 1 or response.shape[0] != values.shape[0]:
        raise ValueError("response must have shape (observations,) or (observations, 1)")
    if not response.is_floating_point():
        raise TypeError("response must be floating point")
    response = response.to(device=values.device, dtype=values.dtype)
    x = values - values.mean(dim=0, keepdim=True)
    y = response - response.mean()
    # Do not use ``sqrt(...).clamp_min(eps)`` here.  Although its *forward*
    # value is finite for a collapsed/constant coordinate, sqrt has an
    # infinite derivative at exactly zero and the ensuing 0*inf path can
    # poison every encoder parameter with NaNs.  Adding eps^2 inside the root
    # retains the same bounded correlation-like forward semantics while making
    # the zero-variance gradient exactly finite (and zero for a constant x).
    x_scale = (x.square().mean(dim=0, keepdim=True) + eps ** 2).sqrt()
    y_scale = (y.square().mean() + eps ** 2).sqrt()
    return (x / x_scale) * (y[:, None] / y_scale)


class JointReplicationTrainingHarness(nn.Module):
    """Connect object formation to observed proposal/replication/null data.

    The input contract is deliberately generic: each environment supplies
    precomputed slot states ``(B, K, D)`` and a scalar observed response
    ``(B,)``.  Adapters, pathology encoders, spatial graphs, and other
    modality-specific models live outside this seam.  ``null_slots`` can be
    one environment ``(B,K,D)`` or a stack ``(E,B,K,D)``; the corresponding
    response may be shared ``(B,)`` or supplied per null ``(E,B)``.

    The proposal dictionary is formed only from ``proposal_slots``.  It is
    detached before any response evidence is scored.  Straight-through values
    retain that dictionary exactly in the forward pass while gradients follow
    the proposal formation state, matching ``evaluate_frozen`` semantics.
    """

    def __init__(self, formation: DifferentiableObjectFormation,
                 critic: ReplicationObjectCritic | None = None,
                 objective_topk: int = 4):
        super().__init__()
        if int(objective_topk) < 1:
            raise ValueError("objective_topk must be positive")
        self.formation = formation
        self.critic = critic if critic is not None else ReplicationObjectCritic()
        # A scientific episode can contain many deliberately opened complete
        # relational alternatives. Averaging every candidate gives one
        # complete but initially rare object a gradient diluted by dozens of
        # unrelated slots. A fixed soft-free top-k routing objective instead
        # asks the representation to improve its best bounded discoveries;
        # each candidate still pays the same replication, null, parent and
        # complexity penalties. This is an optimisation aggregation, not a
        # post-hoc reporting or multiplicity rule.
        self.objective_topk = int(objective_topk)

    def aggregate_critic_value(self, value: torch.Tensor) -> torch.Tensor:
        if value.ndim != 1 or value.numel() < 1:
            raise ValueError("critic value must be a non-empty candidate vector")
        k = min(self.objective_topk, int(value.numel()))
        return torch.topk(value, k=k, largest=True, sorted=False).values.mean()

    @staticmethod
    def _check_slots(slots: torch.Tensor, *, name: str,
                     formation: DifferentiableObjectFormation) -> None:
        if slots.ndim != 3:
            raise ValueError(f"{name} must have shape (observations, slots, dimensions)")
        if slots.shape[1] != formation.n_slots or slots.shape[2] != formation.d_slot:
            raise ValueError(f"{name} does not match object formation slot contract")
        if slots.shape[0] < 2 or not slots.is_floating_point():
            raise ValueError(f"{name} must contain at least two floating-point observations")

    def prepare_dictionary(self, proposal_slots: torch.Tensor) -> tuple[JointObjectOutput, FrozenObjectSelection]:
        """Form and detach the candidate dictionary before response scoring."""
        self._check_slots(proposal_slots, name="proposal_slots", formation=self.formation)
        proposal_output = self.formation(proposal_slots)
        return proposal_output, self.formation.freeze(proposal_output)

    def _frozen_values(self, slots: torch.Tensor, selection: FrozenObjectSelection,
                       gradient_source: JointObjectOutput, *, name: str) -> torch.Tensor:
        self._check_slots(slots, name=name, formation=self.formation)
        return self.formation.evaluate_frozen(slots, selection, gradient_source=gradient_source)

    @staticmethod
    def _as_null_stack(null_slots: torch.Tensor, null_response: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        if null_slots.ndim == 3:
            null_slots = null_slots.unsqueeze(0)
        if null_slots.ndim != 4:
            raise ValueError("null_slots must have shape (B,K,D) or (environments,B,K,D)")
        if null_response.ndim == 1:
            null_response = null_response.unsqueeze(0).expand(null_slots.shape[0], -1)
        elif null_response.ndim == 2 and null_response.shape[0] == 1:
            null_response = null_response.expand(null_slots.shape[0], -1)
        if null_response.ndim != 2 or tuple(null_response.shape) != tuple(null_slots.shape[:2]):
            raise ValueError("null_response must be (B,) or (environments,B), matching null_slots")
        return null_slots, null_response

    @staticmethod
    def _check_atomic_values(values: torch.Tensor | None, *, name: str,
                             observations: int) -> torch.Tensor | None:
        """Validate the compiler-facing atomic readout, without forming it.

        Atomic values are intentionally supplied by the caller rather than
        derived from ``slot_activity``.  The latter is an object-formation
        convenience score; it is not necessarily the named/readout channel
        consumed by the final compiler (for MORPHEUS that channel is the
        factor expert's loading matrix).  ``None`` preserves the historical
        relation-only harness contract.
        """
        if values is None:
            return None
        if not isinstance(values, torch.Tensor) or values.ndim != 2:
            raise ValueError(f"{name} must be a floating tensor with shape (observations, atomic_candidates)")
        if values.shape[0] != observations or values.shape[1] < 1 or not values.is_floating_point():
            raise ValueError(f"{name} must match environment observations and contain at least one floating atomic candidate")
        return values

    @staticmethod
    def _as_null_atomic_stack(null_atomic_values: torch.Tensor | None, *,
                              null_slots: torch.Tensor) -> torch.Tensor | None:
        if null_atomic_values is None:
            return None
        if not isinstance(null_atomic_values, torch.Tensor) or not null_atomic_values.is_floating_point():
            raise ValueError("null_atomic_values must be a floating tensor")
        if null_atomic_values.ndim == 2:
            # A single declared null may use a plain (B,A) readout.  A stack
            # requires each null environment to state its own readout rather
            # than broadcasting an unrelated batch.
            if null_slots.shape[0] != 1:
                raise ValueError("stacked null_slots require null_atomic_values with shape (environments, observations, atomic_candidates)")
            null_atomic_values = null_atomic_values.unsqueeze(0)
        if (null_atomic_values.ndim != 3
                or tuple(null_atomic_values.shape[:2]) != tuple(null_slots.shape[:2])
                or null_atomic_values.shape[2] < 1):
            raise ValueError("null_atomic_values must match null_slots as (environments, observations, atomic_candidates)")
        return null_atomic_values

    def _candidate_provenance(self, selection: FrozenObjectSelection, *,
                              atomic_names: tuple[str, ...] | None,
                              n_atomic: int) -> tuple[Mapping[str, object], ...]:
        if atomic_names is None:
            atomic_names = tuple(f"atomic:{j}" for j in range(n_atomic))
        if len(atomic_names) != n_atomic or len(set(atomic_names)) != n_atomic:
            raise ValueError("atomic_names must be unique and match atomic candidate width")
        atomic = tuple({"kind": "atomic_readout", "id": str(name),
                        "readout_index": j, "complexity": 1.0}
                       for j, name in enumerate(atomic_names))
        relational = tuple({"kind": "frozen_relation", "id": f"joint:{h}",
                            "relation_index": h,
                            "members": tuple(int(x) for x in selection.members[h]),
                            "arity": int(selection.arity[h]),
                            "relation_type_index": int(selection.type_index[h])}
                           for h in range(self.formation.n_objects))
        return atomic + relational

    def _declared_atomic_parent_values(
            self, selection: FrozenObjectSelection, proposal_atomic_values: torch.Tensor,
            replication_atomic_values: torch.Tensor, *, n_atomic: int
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        """Construct lower-complexity parents from a declared atomic channel.

        This is available only when the caller declares that its atomic
        readout columns are in exactly the same order as the object-slot
        dictionary.  It does not search for parents, inspect a response, or
        assume an AND/XOR relation: every frozen multi-member object is tested
        against each of its frozen constituent coordinates.  Atomic candidates
        themselves have no lower-complexity parent in this representation.
        """
        if n_atomic != self.formation.n_slots:
            raise ValueError(
                "derive_atomic_parent_evidence requires one ordered atomic readout "
                "coordinate per object slot")
        max_parents = max((len(members) for members in selection.members), default=0)
        if max_parents < 1:
            raise ValueError("frozen object dictionary contains no declared members")
        n_candidates = n_atomic + self.formation.n_objects
        p_values = proposal_atomic_values.new_zeros(
            max_parents, proposal_atomic_values.shape[0], n_candidates)
        r_values = replication_atomic_values.new_zeros(
            max_parents, replication_atomic_values.shape[0], n_candidates)
        mask = torch.zeros(max_parents, n_candidates, dtype=torch.bool,
                           device=proposal_atomic_values.device)
        parent_complexity = proposal_atomic_values.new_zeros(max_parents, n_candidates)
        for relation_index, members in enumerate(selection.members):
            child = n_atomic + relation_index
            for parent_index, slot_index in enumerate(members):
                if not 0 <= int(slot_index) < n_atomic:
                    raise ValueError("frozen relation member is outside declared atomic readout")
                p_values[parent_index, :, child] = proposal_atomic_values[:, int(slot_index)]
                r_values[parent_index, :, child] = replication_atomic_values[:, int(slot_index)]
                mask[parent_index, child] = True
                parent_complexity[parent_index, child] = 1.0
        return p_values, r_values, parent_complexity, mask

    def forward(self, proposal_slots: torch.Tensor, proposal_response: torch.Tensor,
                replication_slots: torch.Tensor, replication_response: torch.Tensor,
                null_slots: torch.Tensor, null_response: torch.Tensor, *,
                proposal_atomic_values: torch.Tensor | None = None,
                replication_atomic_values: torch.Tensor | None = None,
                null_atomic_values: torch.Tensor | None = None,
                atomic_names: tuple[str, ...] | None = None,
                derive_atomic_parent_evidence: bool = False,
                parent_discovery_evidence: torch.Tensor | None = None,
                parent_replication_evidence: torch.Tensor | None = None,
                parent_complexity: torch.Tensor | None = None,
                parent_mask: torch.Tensor | None = None) -> JointTrainingOutput:
        proposal_output, selection = self.prepare_dictionary(proposal_slots)
        return self.forward_with_selection(
            proposal_slots, proposal_response, replication_slots, replication_response,
            null_slots, null_response, selection=selection,
            proposal_output=proposal_output,
            proposal_atomic_values=proposal_atomic_values,
            replication_atomic_values=replication_atomic_values,
            null_atomic_values=null_atomic_values,
            atomic_names=atomic_names,
            derive_atomic_parent_evidence=derive_atomic_parent_evidence,
            parent_discovery_evidence=parent_discovery_evidence,
            parent_replication_evidence=parent_replication_evidence,
            parent_complexity=parent_complexity,
            parent_mask=parent_mask,
        )

    def forward_with_selection(
            self, proposal_slots: torch.Tensor, proposal_response: torch.Tensor,
            replication_slots: torch.Tensor, replication_response: torch.Tensor,
            null_slots: torch.Tensor, null_response: torch.Tensor, *,
            selection: FrozenObjectSelection,
            proposal_output: JointObjectOutput | None = None,
            proposal_atomic_values: torch.Tensor | None = None,
            replication_atomic_values: torch.Tensor | None = None,
            null_atomic_values: torch.Tensor | None = None,
            atomic_names: tuple[str, ...] | None = None,
            derive_atomic_parent_evidence: bool = False,
            parent_discovery_evidence: torch.Tensor | None = None,
            parent_replication_evidence: torch.Tensor | None = None,
            parent_complexity: torch.Tensor | None = None,
            parent_mask: torch.Tensor | None = None) -> JointTrainingOutput:
        """Score a pre-frozen proposal dictionary with observed responses.

        This is the cadence-safe H1 seam.  A caller forms ``selection`` from
        proposal slots before the response channels are opened, keeps it fixed
        for one declared cadence, and then calls this method for gradient
        updates.  The *forward* values remain exactly those of ``selection``;
        current proposal formation supplies only the straight-through backward
        path.  Thus no response from replication or null environments can
        revise operands, relation type, or arity during the cadence.

        ``proposal_output`` can be reused when the caller already formed it
        while freezing.  Supplying it avoids a duplicate forward pass but does
        not change the selection contract.
        """
        self._check_slots(proposal_slots, name="proposal_slots", formation=self.formation)
        if proposal_output is None:
            proposal_output = self.formation(proposal_slots)
        # Every environment uses the proposal-frozen syntax.  Passing the
        # proposal output as the gradient source makes only the backward path
        # soft; the compiler-facing forward candidate never drifts.
        relational_proposal_values = self._frozen_values(proposal_slots, selection, proposal_output,
                                                         name="proposal_slots")
        relational_replication_values = self._frozen_values(replication_slots, selection, proposal_output,
                                                            name="replication_slots")
        null_slots, null_response = self._as_null_stack(null_slots, null_response)
        relational_null_values = torch.stack([
            self._frozen_values(null_slots[e], selection, proposal_output,
                                name=f"null_slots[{e}]")
            for e in range(null_slots.shape[0])
        ], dim=0)
        proposal_atomic_values = self._check_atomic_values(
            proposal_atomic_values, name="proposal_atomic_values", observations=proposal_slots.shape[0])
        replication_atomic_values = self._check_atomic_values(
            replication_atomic_values, name="replication_atomic_values", observations=replication_slots.shape[0])
        null_atomic_values = self._as_null_atomic_stack(null_atomic_values, null_slots=null_slots)
        supplied = (proposal_atomic_values, replication_atomic_values, null_atomic_values)
        if any(x is None for x in supplied) and not all(x is None for x in supplied):
            raise ValueError("atomic values must be supplied for proposal, replication, and null together")
        if proposal_atomic_values is None:
            n_atomic = 0
            proposal_values = relational_proposal_values
            replication_values = relational_replication_values
            null_values = relational_null_values
        else:
            assert replication_atomic_values is not None and null_atomic_values is not None
            n_atomic = int(proposal_atomic_values.shape[1])
            if (replication_atomic_values.shape[1] != n_atomic
                    or null_atomic_values.shape[2] != n_atomic):
                raise ValueError("atomic candidate width must agree across proposal, replication, and null")
            proposal_values = torch.cat((proposal_atomic_values, relational_proposal_values), dim=1)
            replication_values = torch.cat((replication_atomic_values, relational_replication_values), dim=1)
            null_values = torch.cat((null_atomic_values, relational_null_values), dim=2)
        proposal_evidence = observed_signed_evidence(proposal_values, proposal_response)
        replication_evidence = observed_signed_evidence(replication_values, replication_response)
        null_evidence = torch.stack([
            observed_signed_evidence(null_values[e], null_response[e])
            for e in range(null_values.shape[0])
        ], dim=0)
        # Expected arity provides a smooth, relation-agnostic description cost.
        arities = torch.arange(2, self.formation.max_order + 1,
                               dtype=proposal_values.dtype, device=proposal_values.device)
        relation_complexity = (proposal_output.arity_probabilities * arities).sum(dim=-1)
        complexity = (relation_complexity if n_atomic == 0 else torch.cat(
            (torch.ones(n_atomic, dtype=proposal_values.dtype, device=proposal_values.device),
             relation_complexity), dim=0))
        if derive_atomic_parent_evidence:
            if any(x is not None for x in (
                    parent_discovery_evidence, parent_replication_evidence,
                    parent_complexity, parent_mask)):
                raise ValueError(
                    "derive_atomic_parent_evidence cannot be combined with manually supplied parent evidence")
            if proposal_atomic_values is None or replication_atomic_values is None:
                raise ValueError(
                    "derive_atomic_parent_evidence requires complete declared atomic values")
            parent_p_values, parent_r_values, parent_complexity, parent_mask = (
                self._declared_atomic_parent_values(
                    selection, proposal_atomic_values, replication_atomic_values, n_atomic=n_atomic))
            parent_discovery_evidence = torch.stack([
                observed_signed_evidence(parent_p_values[parent], proposal_response)
                for parent in range(parent_p_values.shape[0])
            ], dim=0)
            parent_replication_evidence = torch.stack([
                observed_signed_evidence(parent_r_values[parent], replication_response)
                for parent in range(parent_r_values.shape[0])
            ], dim=0)
        # Lower-complexity parent alternatives are caller-declared evidence,
        # not an inferred relation-specific feature.  The critic validates
        # their candidate width, stack shape, mask and declared complexity.
        critic = self.critic(
            proposal_evidence, replication_evidence, null_evidence, complexity,
            parent_discovery_evidence=parent_discovery_evidence,
            parent_replication_evidence=parent_replication_evidence,
            parent_complexity=parent_complexity,
            parent_mask=parent_mask,
        )
        # Atomic coordinates remain in the critic as declared lower-order
        # competitors and parents. They cannot, however, monopolise the
        # training top-k: a strong fixed ICA coordinate would then leave every
        # compositional object with zero gradient. The compiler/reporting
        # family remains unchanged and still tests both candidate types.
        objective = self.aggregate_critic_value(critic.value[n_atomic:])
        return JointTrainingOutput(loss=-objective, objective=objective, critic=critic,
                                   selection=selection, proposal_values=proposal_values,
                                   replication_values=replication_values, null_values=null_values,
                                   proposal_evidence=proposal_evidence,
                                   replication_evidence=replication_evidence,
                                   null_evidence=null_evidence,
                                   candidate_provenance=self._candidate_provenance(
                                       selection, atomic_names=atomic_names, n_atomic=n_atomic),
                                   atomic_candidate_count=n_atomic,
                                   relational_candidate_count=self.formation.n_objects,
                                   relational_proposal_values=relational_proposal_values,
                                   relational_replication_values=relational_replication_values,
                                   relational_null_values=relational_null_values)
